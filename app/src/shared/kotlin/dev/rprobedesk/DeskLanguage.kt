internal fun tr(text:String):String = if(UiLanguage.english) englishLabels[text] ?: text else text

private val slot=Regex("""\{(\d+)\}""")
private val messages=englishLabels.filterKeys { "{0}" in it }.map { (key,value) ->
    val pattern=slot.split(key).joinToString("(.+?)") { Regex.escape(it) }
    Regex(pattern) to value
}

internal fun uiMessage(text:String):String {
    if(!UiLanguage.english || text.none { it.code in 0x3400..0x9fff }) return text
    englishLabels[text]?.let { return it }
    if('\n' in text) return text.lines().joinToString("\n",transform=::uiMessage)
    for((pattern,translation) in messages) {
        val match=pattern.matchEntire(text) ?: continue
        return slot.replace(translation) { match.groupValues[it.groupValues[1].toInt()+1] }
    }
    if(" · " in text) return text.split(" · ").joinToString(" · ") { part ->
        val trimmed=part.trim()
        part.replace(trimmed,uiMessage(trimmed))
    }
    return text
}
